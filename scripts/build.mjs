/**
 * Build the three runtime artifacts the bundle manifest exports:
 *
 *   lib/index.js   Host row `jiezi-runtime` (authenticated /api/jiezi routes)
 *   lib/tools.js   preset row `dsh-jiezi/tools` (miniapp_* tools)
 *   lib/client.js  DSH Client module loaded through window.__ModuleLoader__
 *
 * Host code is transpiled file-by-file (not bundled) so the Host row and the
 * preset tools import the same `operations.js` module instance and therefore
 * share one recent-automation list. The Client half must be one self-contained
 * bundle: the page only loads `client.js`, with React and the JSX runtime
 * provided by the Harness module table.
 */

import { build } from 'esbuild';
import { copyFile, cp, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, 'src');
const lib = join(root, 'lib');

async function transpileHost() {
  const entries = {};
  for (const [dir, files] of Object.entries({
    host: ['index.ts', 'tools.ts', 'operations.ts', 'bridge-client.ts', 'bridge-supervisor.ts', 'setup.ts', 'apple-device-host.ts'],
    shared: ['protocol.ts', 'errors.ts'],
  })) {
    for (const file of files) {
      entries[`${dir}/${file.replace(/\.ts$/, '')}`] = join(src, dir, file);
    }
  }
  await build({
    entryPoints: entries,
    outdir: lib,
    outbase: src,
    bundle: false,
    format: 'esm',
    platform: 'node',
    target: ['node20'],
    sourcemap: false,
    logLevel: 'warning',
  });
}

async function copyBridge() {
  const bridgeRoot = join(root, 'vendor', 'bridge');
  const target = join(lib, 'bridge');
  await mkdir(target, { recursive: true });
  const files = (await readdir(join(bridgeRoot, 'src')))
    .filter((file) => file.endsWith('.js'))
    .sort();
  for (const file of files) {
    await copyFile(join(bridgeRoot, 'src', file), join(target, file));
  }
  await copyFile(join(bridgeRoot, 'package.json'), join(target, 'package.json'));
  await cp(join(bridgeRoot, 'templates'), join(target, 'templates'), { recursive: true });
  return files.length;
}

async function writeEntryWrappers() {
  await writeFile(join(lib, 'index.js'), [
    '// Generated by scripts/build.mjs: Host row `jiezi-runtime`.',
    "export { apply, inject, name } from './host/index.js';",
    '',
  ].join('\n'));
  await writeFile(join(lib, 'tools.js'), [
    '// Generated by scripts/build.mjs: preset row `dsh-jiezi/tools`.',
    "export { apply, inject, name } from './host/tools.js';",
    '',
  ].join('\n'));
}

async function buildClient() {
  const result = await build({
    entryPoints: [join(src, 'client/index.tsx')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['es2022', 'chrome120'],
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    define: { 'process.env.NODE_ENV': '"production"' },
    sourcemap: false,
    logLevel: 'warning',
  });
  const code = result.outputFiles[0]?.text ?? '';
  if (code.length === 0) throw new Error('client bundle is empty');
  const indented = code.split('\n').map((line) => (line.length === 0 ? '' : `    ${line}`)).join('\n');
  const wrapped = [
    '// Generated by scripts/build.mjs: DSH Client module for dsh-jiezi.',
    'window.__ModuleLoader__.load({',
    "  id: 'dsh-jiezi',",
    '  factory(require) {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    indented,
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');
  await writeFile(join(lib, 'client.js'), wrapped);
}

async function main() {
  await rm(lib, { recursive: true, force: true });
  await mkdir(lib, { recursive: true });
  await transpileHost();
  const bridgeFiles = await copyBridge();
  await writeEntryWrappers();
  await buildClient();
  const files = (await readdir(lib)).sort();
  console.log(`built ${files.map((file) => `lib/${file}`).join(', ')} (${bridgeFiles} bridge files)`);
}

await main();
